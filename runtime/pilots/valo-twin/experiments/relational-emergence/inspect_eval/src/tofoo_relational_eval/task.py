TASK_VERSION = "1-0"
DEFAULT_SEED = 20260819
DEFAULT_WORLDS = 3
DEFAULT_PARTICIPANTS = 3
DEFAULT_OPERATORS = 3
DEFAULT_ROUNDS = 3

CONDITION = Literal[
    "isolated",
    "pooled_raw",
    "structured_raw",
    "central_iterative",
    "relational_adaptive",
]

QUESTION_HEADER = """Infer the hidden permutation rule for operator {operator}.

Each rule maps a five-character input to an output by selecting input positions in the order shown in the answer choices. The evidence below was generated by one fixed hidden rule. Choose the hidden rule, not merely any rule that happens to fit one local example.

EVIDENCE:
{evidence}
"""

ITERATIVE_TEMPLATE = """Infer the hidden permutation rule for operator {operator}.

The rule catalog is:
{catalog}

All training evidence:
{evidence}

Current central guess from the previous iteration: {prior}

Return exactly one submission line:
ANSWER: <LETTER>
where <LETTER> is one of {letters}.
"""

RELATIONAL_TEMPLATE = """You are participant {participant} in a governed distributed rule-recovery task for operator {operator}.

The rule catalog is:
{catalog}

Your local evidence only:
{evidence}

Current governed field:
{field}

Select one rule that is compatible with your own local evidence. The governed field may help break local ambiguity, but you must not support a rule that contradicts your local evidence.

Return exactly one submission line:
ANSWER: <LETTER>
where <LETTER> is one of {letters}.
"""


def _choice_descriptions() -> list[str]:
    lines = choice_lines().splitlines()
    return [line.split(") ", 1)[1] for line in lines]


def _worlds(seed: int, worlds: int, participants: int, operators: int):
    if worlds < 1:
        raise ValueError("worlds must be >= 1")
    return [
        make_world(
            seed + offset,
            f"W{offset}",
            participants=participants,
            operator_count=operators,
        )
        for offset in range(worlds)
    ]


def _metadata(
    *,
    condition: CONDITION,
    world_id: str,
    operator: str,
    evidence: tuple[Evidence, ...],
    participants: int,
    rounds: int,
) -> dict[str, Any]:
    return {
        "condition": condition,
        "world": world_id,
        "operator": operator,
        "participants": participants,
        "rounds": rounds,
        "evidence": [
            {
                "eid": item.eid,
                "operator": item.operator,
                "inp": item.inp,
                "out": item.out,
                "participant": item.participant,
            }
            for item in evidence
        ],
    }


def _evidence_from_metadata(state: TaskState) -> tuple[Evidence, ...]:
    if state.metadata is None:
        raise ValueError("sample metadata is required")
    return tuple(Evidence(**item) for item in state.metadata["evidence"])


def _multiple_choice_samples(
    condition: Literal["isolated", "pooled_raw", "structured_raw"],
    *,
    seed: int,
    worlds: int,
    participants: int,
    operators: int,
    rounds: int,
) -> list[Sample]:
    samples: list[Sample] = []
    choices = _choice_descriptions()
    for world in _worlds(seed, worlds, participants, operators):
        for operator, truth_rule in world.truth.items():
            all_evidence = world.evidence_for(operator)
            if condition == "isolated":
                groups = [(item,) for item in all_evidence]
            else:
                groups = [all_evidence]

            for group in groups:
                if condition == "structured_raw":
                    ordered = tuple(sorted(group, key=lambda item: item.participant))
                    evidence_text = "\n".join(
                        f"Participant {item.participant}: input={item.inp} output={item.out}"
                        for item in ordered
                    )
                else:
                    evidence_text = format_evidence(group)

                participant_suffix = (
                    f"-P{group[0].participant}" if condition == "isolated" else ""
                )
                sample_id = f"{world.wid}-{operator}-{condition}{participant_suffix}"
                samples.append(
                    Sample(
                        id=sample_id,
                        input=QUESTION_HEADER.format(
                            operator=operator,
                            evidence=evidence_text,
                        ),
                        choices=choices,
                        target=RULE_TO_LETTER[truth_rule],
                        metadata=_metadata(
                            condition=condition,
                            world_id=world.wid,
                            operator=operator,
                            evidence=group,
                            participants=participants,
                            rounds=rounds,
                        ),
                    )
                )
    return samples


def _system_samples(
    condition: Literal["central_iterative", "relational_adaptive"],
    *,
    seed: int,
    worlds: int,
    participants: int,
    operators: int,
    rounds: int,
) -> list[Sample]:
    if rounds < 1:
        raise ValueError("rounds must be >= 1")
    samples: list[Sample] = []
    choices = _choice_descriptions()
    for world in _worlds(seed, worlds, participants, operators):
        for operator, truth_rule in world.truth.items():
            evidence = world.evidence_for(operator)
            samples.append(
                Sample(
                    id=f"{world.wid}-{operator}-{condition}",
                    input=(
                        f"System evaluation: recover the hidden rule for {operator} under "
                        f"condition {condition}."
                    ),
                    choices=choices,
                    target=RULE_TO_LETTER[truth_rule],
                    metadata=_metadata(
                        condition=condition,
                        world_id=world.wid,
                        operator=operator,
                        evidence=evidence,
                        participants=participants,
                        rounds=rounds,
                    ),
                )
            )
    return samples


def _generation_config() -> GenerateConfig:
    return GenerateConfig(temperature=0.0, max_tokens=16)


@solver
def central_iterative_solver() -> Solver:
    async def solve(state: TaskState, generate: Generate) -> TaskState:
        model = get_model()
        evidence = _evidence_from_metadata(state)
        operator = str(state.metadata["operator"])
        participants = int(state.metadata["participants"])
        rounds = int(state.metadata["rounds"])
        prior: str | None = None
        trace: list[dict[str, Any]] = []
        last_output = None

        for step in range(rounds * participants):
            prompt = ITERATIVE_TEMPLATE.format(
                operator=operator,
                catalog=choice_lines(),
                evidence=format_evidence(evidence),
                prior=(prior or "NONE"),
                letters=",".join(LETTERS),
            )
            last_output = await model.generate(prompt, config=_generation_config())
            letter = extract_answer_letter(last_output.completion)
            trace.append({"step": step, "submission": letter})
            if letter is not None:
                prior = letter

        state.metadata["system_answer_letter"] = prior
        state.metadata["system_trace"] = trace
        state.metadata["model_calls"] = rounds * participants
        if last_output is not None:
            state.output = last_output
        return state

    return solve


@solver
def relational_adaptive_solver() -> Solver:
    async def solve(state: TaskState, generate: Generate) -> TaskState:
        model = get_model()
        evidence = _evidence_from_metadata(state)
        operator = str(state.metadata["operator"])
        participants = int(state.metadata["participants"])
        rounds = int(state.metadata["rounds"])
        by_participant = {item.participant: item for item in evidence}
        if set(by_participant) != set(range(participants)):
            raise ValueError("relational sample must contain exactly one evidence item per participant")

        field = GovernedField(participants=participants)
        trace: list[dict[str, Any]] = []
        last_output = None

        for round_id in range(rounds):
            for participant in range(participants):
                local = by_participant[participant]
                prompt = RELATIONAL_TEMPLATE.format(
                    participant=participant,
                    operator=operator,
                    catalog=choice_lines(),
                    evidence=format_evidence((local,)),
                    field=field.render(),
                    letters=",".join(LETTERS),
                )
                last_output = await model.generate(prompt, config=_generation_config())
                letter = extract_answer_letter(last_output.completion)
                selected_rule = LETTER_TO_RULE.get(letter) if letter else None
                locally_compatible = (
                    selected_rule in compatible_rules(local) if selected_rule is not None else False
                )
                mutated = (
                    field.propose(participant, selected_rule, local)
                    if selected_rule is not None
                    else False
                )
                trace.append(
                    {
                        "round": round_id,
                        "participant": participant,
                        "submission": letter,
                        "selected_rule": selected_rule,
                        "locally_compatible": locally_compatible,
                        "field_mutated": mutated,
                        "field_revision": field.revision,
                        "admitted_rule": field.admitted_rule,
                    }
                )

        state.metadata["system_answer_letter"] = (
            RULE_TO_LETTER[field.admitted_rule] if field.admitted_rule else None
        )
        state.metadata["system_trace"] = trace
        state.metadata["field_revision"] = field.revision
        state.metadata["field_admitted_rule"] = field.admitted_rule
        state.metadata["field_unresolved"] = list(field.unresolved)
        state.metadata["model_calls"] = rounds * participants
        if last_output is not None:
            state.output = last_output
        return state

    return solve


@scorer(metrics=[accuracy(), stderr()])
def system_choice_scorer() -> Scorer:
    async def score(state: TaskState, target: Target) -> Score:
        answer = state.metadata.get("system_answer_letter") if state.metadata else None
        correct = answer == target.text
        return Score(
            value=CORRECT if correct else INCORRECT,
            answer=answer or "NO_ADMISSION",
            explanation=(
                "System-level admitted/final choice matched target."
                if correct
                else f"System-level choice {answer!r} did not match target {target.text!r}."
            ),
            metadata={
                "condition": state.metadata.get("condition") if state.metadata else None,
                "world": state.metadata.get("world") if state.metadata else None,
                "operator": state.metadata.get("operator") if state.metadata else None,
                "model_calls": state.metadata.get("model_calls") if state.metadata else None,
                "field_revision": state.metadata.get("field_revision") if state.metadata else None,
                "field_admitted_rule": (
                    state.metadata.get("field_admitted_rule") if state.metadata else None
                ),
            },
        )

    return score


def _task_metadata(condition: CONDITION) -> dict[str, Any]:
    return {
        "evaluation": "tofoo_relational_rule_recovery",
        "condition": condition,
        "claim_scope": "narrow hidden-rule recovery; not a general emergence claim",
        "world_invariant": (
            "each local shard is ambiguous; joint cross-participant evidence uniquely identifies the rule"
        ),
    }


def _mc_task(
    condition: Literal["isolated", "pooled_raw", "structured_raw"],
    *,
    seed: int,
    worlds: int,
    participants: int,
    operators: int,
    rounds: int,
) -> Task:
    return Task(
        dataset=_multiple_choice_samples(
            condition,
            seed=seed,
            worlds=worlds,
            participants=participants,
            operators=operators,
            rounds=rounds,
        ),
        solver=multiple_choice(cot=False, shuffle=False, max_tokens=64),
        scorer=choice(),
        version=TASK_VERSION,
        metadata=_task_metadata(condition),
    )


def _system_task(
    condition: Literal["central_iterative", "relational_adaptive"],
    solver_factory: Callable[[], Solver],
    *,
    seed: int,
    worlds: int,
    participants: int,
    operators: int,
    rounds: int,
) -> Task:
    return Task(
        dataset=_system_samples(
            condition,
            seed=seed,
            worlds=worlds,
            participants=participants,
            operators=operators,
            rounds=rounds,
        ),
        solver=solver_factory(),
        scorer=system_choice_scorer(),
        version=TASK_VERSION,
        metadata=_task_metadata(condition),
    )


